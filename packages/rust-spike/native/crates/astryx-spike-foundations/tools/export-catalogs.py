"""Copy Astryx core's message catalogs into compact per-locale files.

Usage: python3 tools/export-catalogs.py <astryx-repo> catalogs/

Each output line is `key<TAB>message`. A backslash escapes a tab (`\\t`), a
newline (`\\n`) and itself (`\\\\`). Descriptions are dropped: they are for
translators, not for the runtime.
"""
import json, pathlib, sys

src = pathlib.Path(sys.argv[1]) / "packages/core/locales"
out = pathlib.Path(sys.argv[2])
out.mkdir(parents=True, exist_ok=True)
names = []
for f in sorted(src.glob("*.json")):
    data = json.loads(f.read_text())
    lines = []
    for key in sorted(data):
        msg = data[key]["defaultMessage"] if isinstance(data[key], dict) else data[key]
        esc = msg.replace("\\", "\\\\").replace("\t", "\\t").replace("\n", "\\n")
        lines.append(f"{key}\t{esc}")
    (out / f"{f.stem}.tsv").write_text("\n".join(lines) + "\n")
    names.append(f.stem)
rs = ["// Generated by tools/export-catalogs.py. Do not edit.", "pub(crate) static CATALOGS: &[(&str, &str)] = &["]
rs += [f'    ("{n}", include_str!("../../catalogs/{n}.tsv")),' for n in names]
rs += ["];", ""]
(out.parent / "src/i18n/catalogs.rs").write_text("\n".join(rs))
print(len(names), "locales")
