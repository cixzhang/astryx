//! Turns `tokens/themes.json` into typed Rust: one `Tokens` value per theme
//! and mode, so nothing parses JSON at run time.

use serde_json::{Map, Value};
use std::fmt::Write as _;
use std::{env, fs, path::PathBuf};

const THEMES_JSON: &str = "../../tokens/themes.json";
/// The default theme comes first in `Theme::ALL`.
const DEFAULT_THEME: &str = "astryx";

fn main() {
    println!("cargo:rerun-if-changed={THEMES_JSON}");
    println!("cargo:rerun-if-changed=build.rs");
    let source = fs::read_to_string(THEMES_JSON).expect("read tokens/themes.json");
    let root: Map<String, Value> = serde_json::from_str(&source).expect("parse tokens/themes.json");

    let mut names: Vec<&String> = root.keys().collect();
    names.sort_by_key(|name| (name.as_str() != DEFAULT_THEME, name.as_str()));
    let reference = &root[DEFAULT_THEME]["light"];

    let mut out = String::new();
    out.push_str("// Generated by build.rs from tokens/themes.json. Do not edit.\n\n");
    write_types(&mut out, reference);
    for name in &names {
        let theme = obj(&root[name.as_str()]);
        for mode in ["light", "dark"] {
            check_shape(reference, &theme[mode], &format!("{name}.{mode}"));
        }
        let ident = name.to_uppercase();
        writeln!(out, "/// The `{name}` theme.").unwrap();
        writeln!(out, "pub static {ident}_THEME: Theme = Theme {{").unwrap();
        writeln!(out, "    name: {name:?},").unwrap();
        for mode in ["light", "dark"] {
            writeln!(out, "    {mode}: {},", tokens_value(&theme[mode])).unwrap();
        }
        out.push_str("};\n\n");
    }
    out.push_str("impl Theme {\n");
    for name in &names {
        let ident = name.to_uppercase();
        writeln!(out, "    /// The `{name}` theme.").unwrap();
        writeln!(
            out,
            "    pub const {ident}: &'static Theme = &{ident}_THEME;"
        )
        .unwrap();
    }
    out.push_str("    /// Every published theme, the default (`astryx`) first.\n");
    let all: Vec<String> = names
        .iter()
        .map(|n| format!("Theme::{}", n.to_uppercase()))
        .collect();
    writeln!(
        out,
        "    pub const ALL: &'static [&'static Theme] = &[{}];",
        all.join(", ")
    )
    .unwrap();
    out.push_str("}\n");

    let dest = PathBuf::from(env::var("OUT_DIR").unwrap()).join("tokens.rs");
    fs::write(dest, out).expect("write generated tokens");
}

fn obj(value: &Value) -> &Map<String, Value> {
    value.as_object().expect("expected a JSON object")
}

fn num(value: &Value) -> f32 {
    value.as_f64().expect("expected a number") as f32
}

/// `backgroundBody` -> `background_body`; `s0_5` stays as it is.
fn snake(name: &str) -> String {
    let mut out = String::with_capacity(name.len() + 4);
    for (i, ch) in name.chars().enumerate() {
        if ch.is_ascii_uppercase() {
            if i > 0 {
                out.push('_');
            }
            out.push(ch.to_ascii_lowercase());
        } else {
            out.push(ch);
        }
    }
    out
}

/// Every theme and mode must have the members of the default light tokens,
/// because they all share one set of Rust types.
fn check_shape(reference: &Value, other: &Value, path: &str) {
    match (reference, other) {
        (Value::Object(a), Value::Object(b)) => {
            let (mut ka, mut kb): (Vec<_>, Vec<_>) = (a.keys().collect(), b.keys().collect());
            ka.sort();
            kb.sort();
            assert_eq!(ka, kb, "token members differ at {path}");
            // Shadow layers and type styles are checked by their own readers.
            if a.contains_key("rgba") {
                return;
            }
            for key in ka {
                if !a[key].is_array() {
                    check_shape(&a[key], &b[key], &format!("{path}.{key}"));
                }
            }
        }
        (Value::Array(_), Value::Array(_)) => {}
        (Value::Number(_), Value::Number(_)) => {}
        _ => panic!("token kinds differ at {path}"),
    }
}

fn group_struct(out: &mut String, name: &str, doc: &str, members: &Map<String, Value>, ty: &str) {
    writeln!(out, "/// {doc}").unwrap();
    out.push_str("#[derive(Clone, Copy, Debug, PartialEq)]\n");
    writeln!(out, "pub struct {name} {{").unwrap();
    for key in members.keys() {
        writeln!(out, "    /// `{key}`").unwrap();
        writeln!(out, "    pub {}: {ty},", snake(key)).unwrap();
    }
    out.push_str("}\n\n");
}

fn write_types(out: &mut String, tokens: &Value) {
    let t = obj(tokens);
    group_struct(
        out,
        "ColorTokens",
        "Semantic colors, straight sRGB.",
        obj(&t["color"]),
        "Rgba",
    );
    group_struct(
        out,
        "SpaceTokens",
        "The spacing scale in points: `sN` is step N.",
        obj(&t["space"]),
        "f32",
    );
    group_struct(
        out,
        "RadiusTokens",
        "Corner radii in points.",
        obj(&t["radius"]),
        "f32",
    );
    group_struct(
        out,
        "SizeTokens",
        "Element heights and the border width, in points.",
        obj(&t["size"]),
        "f32",
    );

    let font = obj(&t["font"]);
    group_struct(
        out,
        "FontFamilyTokens",
        "Font family stacks, most preferred first.",
        obj(&font["family"]),
        "&'static [&'static str]",
    );
    group_struct(
        out,
        "FontSizeTokens",
        "The type scale's raw sizes in points.",
        obj(&font["size"]),
        "f32",
    );
    group_struct(
        out,
        "FontWeightTokens",
        "Named CSS font weights.",
        obj(&font["weight"]),
        "u16",
    );
    out.push_str("/// Type styles, plus the raw families, sizes, and weights they draw from.\n");
    out.push_str("#[derive(Clone, Copy, Debug, PartialEq)]\npub struct FontTokens {\n");
    for (key, value) in font {
        let ty = match key.as_str() {
            "family" => "FontFamilyTokens",
            "size" => "FontSizeTokens",
            "weight" => "FontWeightTokens",
            _ => {
                assert!(
                    value.get("leading").is_some(),
                    "font.{key} is not a type style"
                );
                "TypeStyle"
            }
        };
        writeln!(out, "    /// `{key}`\n    pub {}: {ty},", snake(key)).unwrap();
    }
    out.push_str("}\n\n");

    group_struct(
        out,
        "ShadowTokens",
        "Elevation shadows, each a stack of layers.",
        obj(&t["shadow"]),
        "&'static [ShadowLayer]",
    );
}

fn rgba(value: &Value) -> String {
    let c = value["rgba"].as_array().expect("color without rgba");
    assert_eq!(c.len(), 4);
    format!(
        "[{:?}, {:?}, {:?}, {:?}]",
        num(&c[0]),
        num(&c[1]),
        num(&c[2]),
        num(&c[3])
    )
}

fn group_value(
    name: &str,
    members: &Map<String, Value>,
    item: impl Fn(&Value) -> String,
) -> String {
    let fields: Vec<String> = members
        .iter()
        .map(|(k, v)| format!("{}: {}", snake(k), item(v)))
        .collect();
    format!("{name} {{ {} }}", fields.join(", "))
}

fn tokens_value(tokens: &Value) -> String {
    let t = obj(tokens);
    let font = obj(&t["font"]);
    let font_fields: Vec<String> = font
        .iter()
        .map(|(key, value)| {
            let v = match key.as_str() {
                "family" => group_value("FontFamilyTokens", obj(value), |stack| {
                    let names: Vec<String> = stack
                        .as_array()
                        .unwrap()
                        .iter()
                        .map(|n| format!("{:?}", n.as_str().unwrap()))
                        .collect();
                    format!("&[{}]", names.join(", "))
                }),
                "size" => group_value("FontSizeTokens", obj(value), |v| format!("{:?}", num(v))),
                "weight" => group_value("FontWeightTokens", obj(value), |v| {
                    format!("{}", num(v) as u16)
                }),
                _ => format!(
                    "TypeStyle {{ size: {:?}, weight: {}, leading: {:?} }}",
                    num(&value["size"]),
                    num(&value["weight"]) as u16,
                    num(&value["leading"])
                ),
            };
            format!("{}: {v}", snake(key))
        })
        .collect();
    let shadow = group_value("ShadowTokens", obj(&t["shadow"]), |layers| {
        let layers: Vec<String> = layers
            .as_array()
            .expect("shadow is a list of layers")
            .iter()
            .map(|l| {
                format!(
                    "ShadowLayer {{ x: {:?}, y: {:?}, blur: {:?}, spread: {:?}, is_inset: {}, color: {} }}",
                    num(&l["x"]),
                    num(&l["y"]),
                    num(&l["blur"]),
                    l.get("spread").map_or(0.0, num),
                    l.get("isInset").and_then(Value::as_bool).unwrap_or(false),
                    rgba(&l["color"]),
                )
            })
            .collect();
        format!("&[{}]", layers.join(", "))
    });
    format!(
        "Tokens {{ color: {}, space: {}, radius: {}, size: {}, font: FontTokens {{ {} }}, shadow: {} }}",
        group_value("ColorTokens", obj(&t["color"]), rgba),
        group_value("SpaceTokens", obj(&t["space"]), |v| format!("{:?}", num(v))),
        group_value("RadiusTokens", obj(&t["radius"]), |v| format!("{:?}", num(v))),
        group_value("SizeTokens", obj(&t["size"]), |v| format!("{:?}", num(v))),
        font_fields.join(", "),
        shadow,
    )
}
