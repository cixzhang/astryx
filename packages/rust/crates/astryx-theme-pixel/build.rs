//! Turns `tokens/pixel-themes.json` (lengths in pixel units) and
//! `tokens/pixel-icons.json` into Rust: unit tokens per palette and mode, a
//! function that scales them by the pixel size, and the bitmap icons.

use serde_json::{Map, Value};
use std::fmt::Write as _;
use std::{env, fs, path::PathBuf};

const THEMES: &str = "../../tokens/pixel-themes.json";
const ICONS: &str = "../../tokens/pixel-icons.json";
/// Icons the source theme lacks, drawn for this port in the same style.
const EXTRA_ICONS: &str = "extra-icons.json";
const PALETTES: [&str; 5] = ["garden", "gameboy", "nes", "c64", "pico8"];

fn main() {
    for path in [THEMES, ICONS, EXTRA_ICONS, "build.rs"] {
        println!("cargo:rerun-if-changed={path}");
    }
    let themes: Map<String, Value> =
        serde_json::from_str(&fs::read_to_string(THEMES).expect("read pixel-themes.json"))
            .expect("parse pixel-themes.json");
    let mut icons: Map<String, Value> =
        serde_json::from_str(&fs::read_to_string(ICONS).expect("read pixel-icons.json"))
            .expect("parse pixel-icons.json");
    let extra: Map<String, Value> =
        serde_json::from_str(&fs::read_to_string(EXTRA_ICONS).expect("read extra-icons.json"))
            .expect("parse extra-icons.json");
    for (name, rows) in extra {
        assert!(
            !icons.contains_key(&name),
            "{name} is in the source icons now"
        );
        icons.insert(name, rows);
    }

    let mut out = String::from("// Generated by build.rs. Do not edit.\n\n");
    out.push_str("/// Unit tokens (pixel size 1), by palette then light and dark.\n");
    out.push_str("static UNIT: [[Tokens; 2]; 5] = [\n");
    for palette in PALETTES {
        let modes = &themes[palette];
        writeln!(
            out,
            "    [{}, {}],",
            tokens_value(&modes["light"]),
            tokens_value(&modes["dark"])
        )
        .unwrap();
    }
    out.push_str("];\n\n");
    write_scale(&mut out, &themes[PALETTES[0]]["light"]);

    out.push_str("/// The pixel theme's icons: 12 by 12 cells, `#` filled.\n");
    out.push_str("pub static ICONS: &[BitmapIcon] = &[\n");
    for (name, rows) in &icons {
        let rows: Vec<String> = rows
            .as_array()
            .expect("icon rows")
            .iter()
            .map(|r| format!("{:?}", r.as_str().expect("row text")))
            .collect();
        writeln!(
            out,
            "    BitmapIcon {{ name: {name:?}, rows: &[{}] }},",
            rows.join(", ")
        )
        .unwrap();
    }
    out.push_str("];\n");

    let dest = PathBuf::from(env::var("OUT_DIR").unwrap()).join("pixel.rs");
    fs::write(dest, out).expect("write generated pixel tokens");
}

fn obj(value: &Value) -> &Map<String, Value> {
    value.as_object().expect("expected a JSON object")
}

fn num(value: &Value) -> f32 {
    value.as_f64().expect("expected a number") as f32
}

/// `backgroundBody` -> `background_body`.
fn snake(name: &str) -> String {
    let mut out = String::new();
    for (i, ch) in name.chars().enumerate() {
        if ch.is_ascii_uppercase() {
            if i > 0 {
                out.push('_');
            }
            out.push(ch.to_ascii_lowercase());
        } else {
            out.push(ch);
        }
    }
    out
}

fn rgba(value: &Value) -> String {
    let c = value["rgba"].as_array().expect("color without rgba");
    let c: Vec<String> = c.iter().map(|v| format!("{:?}", num(v))).collect();
    format!("[{}]", c.join(", "))
}

fn group(name: &str, members: &Map<String, Value>, item: impl Fn(&Value) -> String) -> String {
    let fields: Vec<String> = members
        .iter()
        .map(|(k, v)| format!("{}: {}", snake(k), item(v)))
        .collect();
    format!("{name} {{ {} }}", fields.join(", "))
}

fn tokens_value(tokens: &Value) -> String {
    let t = obj(tokens);
    let font: Vec<String> = obj(&t["font"])
        .iter()
        .map(|(key, value)| {
            let v = match key.as_str() {
                "family" => group("FontFamilyTokens", obj(value), |stack| {
                    let names: Vec<String> = stack
                        .as_array()
                        .unwrap()
                        .iter()
                        .map(|n| format!("{:?}", n.as_str().unwrap()))
                        .collect();
                    format!("&[{}]", names.join(", "))
                }),
                "size" => group("FontSizeTokens", obj(value), |v| format!("{:?}", num(v))),
                "weight" => group("FontWeightTokens", obj(value), |v| {
                    format!("{}", num(v) as u16)
                }),
                _ => format!(
                    "TypeStyle {{ size: {:?}, weight: {}, leading: {:?} }}",
                    num(&value["size"]),
                    num(&value["weight"]) as u16,
                    num(&value["leading"])
                ),
            };
            format!("{}: {v}", snake(key))
        })
        .collect();
    let shadow = group("ShadowTokens", obj(&t["shadow"]), |layers| {
        let layers: Vec<String> = layers
            .as_array()
            .unwrap()
            .iter()
            .map(|l| {
                format!(
                    "ShadowLayer {{ x: {:?}, y: {:?}, blur: {:?}, spread: {:?}, is_inset: {}, color: {} }}",
                    num(&l["x"]),
                    num(&l["y"]),
                    num(&l["blur"]),
                    l.get("spread").map_or(0.0, num),
                    l.get("isInset").and_then(Value::as_bool).unwrap_or(false),
                    rgba(&l["color"]),
                )
            })
            .collect();
        format!("&[{}]", layers.join(", "))
    });
    format!(
        "Tokens {{ color: {}, space: {}, radius: {}, size: {}, font: FontTokens {{ {} }}, shadow: {} }}",
        group("ColorTokens", obj(&t["color"]), rgba),
        group("SpaceTokens", obj(&t["space"]), |v| format!("{:?}", num(v))),
        group("RadiusTokens", obj(&t["radius"]), |v| format!("{:?}", num(v))),
        group("SizeTokens", obj(&t["size"]), |v| format!("{:?}", num(v))),
        font.join(", "),
        shadow,
    )
}

/// `fn scale(unit, p) -> Tokens`: every length times `p`. Colors, weights,
/// leadings, and the `full` radius stay as they are.
fn write_scale(out: &mut String, tokens: &Value) {
    let t = obj(tokens);
    out.push_str("/// `unit` with every length multiplied by `p`.\n");
    out.push_str("fn scale(unit: &Tokens, p: f32) -> Tokens {\n    let mut t = *unit;\n");
    for group in ["space", "radius", "size"] {
        for key in obj(&t[group]).keys() {
            if group == "radius" && key == "full" {
                continue;
            }
            let f = snake(key);
            writeln!(out, "    t.{group}.{f} *= p;").unwrap();
        }
    }
    for (key, value) in obj(&t["font"]) {
        match key.as_str() {
            "family" | "weight" => {}
            "size" => {
                for k in obj(value).keys() {
                    writeln!(out, "    t.font.size.{} *= p;", snake(k)).unwrap();
                }
            }
            _ => writeln!(out, "    t.font.{}.size *= p;", snake(key)).unwrap(),
        }
    }
    for key in obj(&t["shadow"]).keys() {
        writeln!(
            out,
            "    t.shadow.{key} = scale_shadow(unit.shadow.{key}, p);"
        )
        .unwrap();
    }
    out.push_str("    t\n}\n\n");
}
