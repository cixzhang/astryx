//! Turns `tokens/motion.json` into typed Rust: one `MotionTokens` value per
//! theme, the fixed motion values, and the spring roles, so nothing parses
//! JSON at run time.

use serde_json::Value;
use std::fmt::Write as _;
use std::{env, fs, path::PathBuf};

const MOTION_JSON: &str = "../../tokens/motion.json";
const DEFAULT_THEME: &str = "astryx";

fn main() {
    println!("cargo:rerun-if-changed={MOTION_JSON}");
    println!("cargo:rerun-if-changed=build.rs");
    let source = fs::read_to_string(MOTION_JSON).expect("read tokens/motion.json");
    let root: Value = serde_json::from_str(&source).expect("parse tokens/motion.json");
    let mut out =
        String::from("// Generated by build.rs from tokens/motion.json. Do not edit.\n\n");

    let themes = root["themes"].as_object().expect("themes");
    let mut names: Vec<&String> = themes.keys().collect();
    names.sort_by_key(|name| (name.as_str() != DEFAULT_THEME, name.as_str()));
    for name in &names {
        let t = &themes[name.as_str()];
        let d = &t["duration"];
        let e = &t["ease"];
        let ident = name.to_uppercase();
        writeln!(out, "/// The `{name}` theme's motion tokens.").unwrap();
        writeln!(out, "pub static {ident}: MotionTokens = MotionTokens {{").unwrap();
        writeln!(out, "    name: {name:?},").unwrap();
        writeln!(
            out,
            "    knobs: ResolvedKnobs {{ tempo: {}, character: Character::{}, reduced_motion: ThemeReducedMotion::{}, tempo_is_set: false }},",
            f(&t["knobs"]["tempo"]),
            pascal(t["knobs"]["character"].as_str().unwrap()),
            pascal(t["knobs"]["reducedMotion"].as_str().unwrap()),
        )
        .unwrap();
        writeln!(
            out,
            "    duration_scale: {},",
            t["durationScale"].as_bool().unwrap()
        )
        .unwrap();
        writeln!(
            out,
            "    easing_override: {},",
            t["easingOverride"].as_bool().unwrap()
        )
        .unwrap();
        out.push_str("    durations: Durations {\n");
        for key in [
            "fast-min",
            "fast",
            "fast-max",
            "medium-min",
            "medium",
            "medium-max",
            "slow-min",
            "slow",
            "slow-max",
            "exit",
        ] {
            writeln!(out, "        {}: {},", key.replace('-', "_"), f(&d[key])).unwrap();
        }
        out.push_str("        exit_dialog: EXIT_KIND_DEFAULT_MS,\n        exit_layer: EXIT_KIND_DEFAULT_MS,\n    },\n");
        for key in ["standard", "entrance", "move", "exit"] {
            writeln!(out, "    ease_{key}: {},", bezier(&e[key])).unwrap();
        }
        out.push_str("};\n\n");
    }
    out.push_str("/// Every published theme's motion tokens, the default (`astryx`) first.\n");
    let all: Vec<String> = names
        .iter()
        .map(|n| format!("&{}", n.to_uppercase()))
        .collect();
    writeln!(
        out,
        "pub static ALL: [&MotionTokens; {}] = [{}];\n",
        all.len(),
        all.join(", ")
    )
    .unwrap();

    let knobs = &root["knobs"];
    let range = knobs["tempoRange"].as_array().unwrap();
    writeln!(
        out,
        "/// The range `tempo` is clamped to (`spec:AST-108` FR1)."
    )
    .unwrap();
    writeln!(
        out,
        "pub const TEMPO_RANGE: (f32, f32) = ({}, {});",
        f(&range[0]),
        f(&range[1])
    )
    .unwrap();
    writeln!(
        out,
        "/// The entrance and move curve at `crisp` (`spec:AST-108` FR2)."
    )
    .unwrap();
    writeln!(
        out,
        "pub const CRISP_EASE: CubicBezier = {};",
        bezier(&knobs["characterEase"]["crisp"])
    )
    .unwrap();
    writeln!(
        out,
        "/// The entrance and move curve at `expressive` (`spec:AST-108` FR2)."
    )
    .unwrap();
    writeln!(
        out,
        "pub const EXPRESSIVE_EASE: CubicBezier = {};",
        bezier(&knobs["characterEase"]["expressive"])
    )
    .unwrap();
    let fade = &root["reducedMotionCrossFade"];
    writeln!(
        out,
        "/// The Reduce Motion cross-fade, at most this long (`design:reduced-motion` DR2)."
    )
    .unwrap();
    writeln!(
        out,
        "pub const REDUCED_MOTION_CROSS_FADE_MS: f32 = {};",
        f(&fade["ms"])
    )
    .unwrap();
    writeln!(out, "/// The Reduce Motion cross-fade's curve.").unwrap();
    writeln!(
        out,
        "pub const REDUCED_MOTION_CROSS_FADE_CURVE: CubicBezier = {};",
        bezier(&fade["curve"])
    )
    .unwrap();
    writeln!(
        out,
        "/// A press's highlight onset, in ms: none, it shows in the frame the press lands."
    )
    .unwrap();
    writeln!(
        out,
        "pub const PRESS_HIGHLIGHT_IN_MS: f32 = {};",
        f(&root["press"]["highlightInMs"])
    )
    .unwrap();
    writeln!(
        out,
        "/// How long a held press waits before it becomes a long press, in ms."
    )
    .unwrap();
    writeln!(
        out,
        "pub const LONG_PRESS_MS: f32 = {};",
        f(&root["longPress"]["ms"])
    )
    .unwrap();
    writeln!(
        out,
        "/// How far a pointer may move before a pending long press fails, in px."
    )
    .unwrap();
    writeln!(
        out,
        "pub const LONG_PRESS_ALLOWABLE_MOVEMENT_PX: f32 = {};\n",
        f(&root["longPress"]["allowableMovementPx"])
    )
    .unwrap();

    out.push_str("/// The springs `spec:AST-094` FR4 names, at tempo 1.\npub mod springs {\n    use crate::spring::SpringSpec;\n");
    let springs = root["springs"].as_object().unwrap();
    for (name, s) in springs {
        let spec = if s.get("response").is_some() {
            format!(
                "SpringSpec::Response {{ response: {}, damping_ratio: {} }}",
                f(&s["response"]),
                f(&s["dampingRatio"])
            )
        } else if s.get("bounce").is_some() {
            format!(
                "SpringSpec::DurationBounce {{ duration: {}, bounce: {} }}",
                f(&s["duration"]),
                f(&s["bounce"])
            )
        } else {
            format!(
                "SpringSpec::Physics {{ mass: {}, stiffness: {}, damping: {} }}",
                f(&s["mass"]),
                f(&s["stiffness"]),
                f(&s["damping"])
            )
        };
        writeln!(out, "    /// `springs.{name}`.").unwrap();
        writeln!(
            out,
            "    pub const {}: SpringSpec = {spec};",
            snake(name).to_uppercase()
        )
        .unwrap();
    }
    out.push_str("}\n");

    let dest = PathBuf::from(env::var("OUT_DIR").unwrap()).join("motion_tokens.rs");
    fs::write(dest, out).expect("write motion_tokens.rs");
}

fn f(v: &Value) -> String {
    let x = v.as_f64().expect("number");
    format!("{x:?}_f32")
}

fn bezier(v: &Value) -> String {
    let p: Vec<String> = v.as_array().expect("curve").iter().map(f).collect();
    format!("CubicBezier::new({})", p.join(", "))
}

fn pascal(s: &str) -> String {
    let mut c = s.chars();
    c.next()
        .map(|h| h.to_ascii_uppercase().to_string() + c.as_str())
        .unwrap_or_default()
}

fn snake(s: &str) -> String {
    let mut out = String::new();
    for ch in s.chars() {
        if ch.is_ascii_uppercase() {
            out.push('_');
            out.push(ch.to_ascii_lowercase());
        } else {
            out.push(ch);
        }
    }
    out
}
